"""Main FastAPI entrypoint for Daleel Evidence RAG."""
from fastapi import FastAPI
from pydantic import BaseModel
from typing import Optional, List, Dict, Any

app = FastAPI(
    title="Daleel Evidence-Based Medicine API",
    description="Agentic RAG for biomedical literature retrieval and synthesis",
    version="0.1.0"
)

class QueryRequest(BaseModel):
    query: str
    top_k: Optional[int] = 5

class QueryResponse(BaseModel):
    query: str
    answer: str
    citations: List[Dict[str, Any]]
    confidence_score: float

@app.get("/health")
def health_check():
    return {"status": "ok", "app": "daleel"}

@app.post("/query", response_model=QueryResponse)
async def query_evidence(request: QueryRequest):
    return QueryResponse(
        query=request.query,
        answer="Placeholder answer generated by Daleel workflow.",
        citations=[],
        confidence_score=0.95
    )